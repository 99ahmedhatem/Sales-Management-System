create table if not exists public.activity_logs (
  id uuid primary key default gen_random_uuid(),
  lead_id uuid not null references public.leads(id) on delete cascade,
  actor_id uuid not null references auth.users(id) on delete cascade,
  actor_name text not null,
  actor_role text not null,
  activity_type text not null check (activity_type in ('call', 'comment', 'assignment', 'forward')),
  outcome text,
  notes text,
  created_at timestamptz not null default now()
);

alter table public.activity_logs enable row level security;

do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'activity_logs' and policyname = 'Authenticated users can read activity logs') then
    create policy "Authenticated users can read activity logs"
      on public.activity_logs for select to authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'activity_logs' and policyname = 'Users can add their activity logs') then
    create policy "Users can add their activity logs"
      on public.activity_logs for insert to authenticated with check (auth.uid() = actor_id);
  end if;
end $$;

create index if not exists activity_logs_lead_created_idx
  on public.activity_logs (lead_id, created_at desc);

