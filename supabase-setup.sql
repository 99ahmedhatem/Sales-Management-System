create or replace function public.set_lead_customer_number(target_lead_id uuid, new_customer_number bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if new_customer_number is not null and new_customer_number <= 0 then
    raise exception 'Customer number must be positive';
  end if;

  update public.leads
  set customer_number = new_customer_number
  where id = target_lead_id;
end;
$$;

grant execute on function public.set_lead_customer_number(uuid, bigint) to authenticated;

